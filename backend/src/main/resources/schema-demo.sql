CREATE TABLE IF NOT EXISTS rol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE,
    descripcion VARCHAR(200)
);
CREATE TABLE IF NOT EXISTS usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id BIGINT NOT NULL REFERENCES rol(id) ON DELETE RESTRICT,
    correo VARCHAR(120) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS proyecto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    ubicacion VARCHAR(250),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS etapa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL REFERENCES proyecto(id) ON DELETE RESTRICT,
    nombre VARCHAR(100) NOT NULL,
    orden INTEGER NOT NULL CHECK (orden > 0),
    UNIQUE (proyecto_id, orden),
    UNIQUE (proyecto_id, nombre)
);
CREATE TABLE IF NOT EXISTS manzana (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etapa_id BIGINT NOT NULL REFERENCES etapa(id) ON DELETE RESTRICT,
    codigo VARCHAR(30) NOT NULL,
    UNIQUE (etapa_id, codigo)
);
CREATE TABLE IF NOT EXISTS lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manzana_id BIGINT NOT NULL REFERENCES manzana(id) ON DELETE RESTRICT,
    codigo VARCHAR(30) NOT NULL,
    area_m2 NUMERIC(12,2) NOT NULL CHECK (area_m2 > 0),
    precio NUMERIC(14,2) NOT NULL CHECK (precio > 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE'
        CHECK (estado IN ('DISPONIBLE','RESERVADO','VENDIDO','NO_DISPONIBLE')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    UNIQUE (manzana_id, codigo)
);
CREATE TABLE IF NOT EXISTS plan_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL REFERENCES proyecto(id) ON DELETE RESTRICT,
    nombre VARCHAR(100) NOT NULL,
    inicial NUMERIC(14,2) NOT NULL CHECK (inicial >= 0),
    numero_cuotas INTEGER NOT NULL CHECK (numero_cuotas > 0),
    monto_cuota NUMERIC(14,2) NOT NULL CHECK (monto_cuota > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (proyecto_id, nombre)
);
CREATE TABLE IF NOT EXISTS lote_plan_pago (
    lote_id BIGINT NOT NULL REFERENCES lote(id) ON DELETE CASCADE,
    plan_pago_id BIGINT NOT NULL REFERENCES plan_pago(id) ON DELETE RESTRICT,
    PRIMARY KEY (lote_id, plan_pago_id)
);
CREATE TABLE IF NOT EXISTS cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(30) NOT NULL,
    nombre VARCHAR(160) NOT NULL,
    telefono VARCHAR(30),
    correo VARCHAR(120),
    fecha_registro TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uq_cliente_documento UNIQUE (tipo_documento, numero_documento)
);
CREATE TABLE IF NOT EXISTS cliente_relacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    relacionado_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('COTITULAR','CONYUGE','OTRO')),
    CHECK (cliente_id <> relacionado_id),
    UNIQUE (cliente_id, relacionado_id, tipo)
);
CREATE TABLE IF NOT EXISTS cliente_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    tipo VARCHAR(30) NOT NULL,
    lado VARCHAR(10) NOT NULL CHECK (lado IN ('ANVERSO','REVERSO')),
    ruta_privada VARCHAR(500) NOT NULL,
    fecha_carga TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    UNIQUE (cliente_id, tipo, lado)
);
CREATE TABLE IF NOT EXISTS separacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES lote(id) ON DELETE RESTRICT,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    asesor_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    monto NUMERIC(14,2) NOT NULL CHECK (monto > 0),
    fecha_registro TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA','CONFIRMADA','ANULADA','VENCIDA')),
    observacion VARCHAR(500)
);
