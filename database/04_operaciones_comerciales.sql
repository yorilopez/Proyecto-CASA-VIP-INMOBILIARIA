CREATE TABLE IF NOT EXISTS auditoria_comercial (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), entidad VARCHAR(30) NOT NULL,
 registro_id BIGINT NOT NULL, accion VARCHAR(40) NOT NULL, motivo VARCHAR(500) NOT NULL,
 anterior TEXT, actual TEXT, fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS operacion_documento (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 separacion_id BIGINT NOT NULL REFERENCES separacion(id), persona VARCHAR(160) NOT NULL,
 lado VARCHAR(10) NOT NULL, ruta_privada VARCHAR(500) NOT NULL
);
CREATE TABLE IF NOT EXISTS notificacion (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 operacion_id BIGINT REFERENCES separacion(id), tipo VARCHAR(30) NOT NULL,
 titulo VARCHAR(160) NOT NULL, mensaje VARCHAR(500) NOT NULL,
 fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS notificacion_lectura (
 usuario_id BIGINT NOT NULL REFERENCES usuario(id), notificacion_id BIGINT NOT NULL REFERENCES notificacion(id),
 fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(), PRIMARY KEY(usuario_id,notificacion_id)
);
CREATE INDEX IF NOT EXISTS ix_auditoria_entidad ON auditoria_comercial(entidad,registro_id,id);
CREATE INDEX IF NOT EXISTS ix_operacion_documento ON operacion_documento(separacion_id);
CREATE INDEX IF NOT EXISTS ix_notificacion_fecha ON notificacion(id);
