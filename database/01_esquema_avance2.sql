BEGIN;

CREATE TABLE rol (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(40) NOT NULL UNIQUE,
    descripcion VARCHAR(200)
);
CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rol_id BIGINT NOT NULL REFERENCES rol(id) ON DELETE RESTRICT,
    correo VARCHAR(120) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE proyecto (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(160) NOT NULL,
    ubicacion VARCHAR(250),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE etapa (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL REFERENCES proyecto(id) ON DELETE RESTRICT,
    nombre VARCHAR(100) NOT NULL,
    orden INTEGER NOT NULL CHECK (orden > 0),
    UNIQUE (proyecto_id, orden),
    UNIQUE (proyecto_id, nombre)
);
CREATE TABLE manzana (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    etapa_id BIGINT NOT NULL REFERENCES etapa(id) ON DELETE RESTRICT,
    codigo VARCHAR(30) NOT NULL,
    UNIQUE (etapa_id, codigo)
);
CREATE TABLE lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    manzana_id BIGINT NOT NULL REFERENCES manzana(id) ON DELETE RESTRICT,
    codigo VARCHAR(30) NOT NULL,
    area_m2 NUMERIC(12,2) NOT NULL CHECK (area_m2 > 0),
    precio NUMERIC(14,2) NOT NULL CHECK (precio > 0),
    estado VARCHAR(20) NOT NULL DEFAULT 'DISPONIBLE'
        CHECK (estado IN ('DISPONIBLE','RESERVADO','VENDIDO','NO_DISPONIBLE')),
    version BIGINT NOT NULL DEFAULT 0 CHECK (version >= 0),
    UNIQUE (manzana_id, codigo)
);
CREATE TABLE plan_pago (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proyecto_id BIGINT NOT NULL REFERENCES proyecto(id) ON DELETE RESTRICT,
    nombre VARCHAR(100) NOT NULL,
    inicial NUMERIC(14,2) NOT NULL CHECK (inicial >= 0),
    numero_cuotas INTEGER NOT NULL CHECK (numero_cuotas > 0),
    monto_cuota NUMERIC(14,2) NOT NULL CHECK (monto_cuota > 0),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (proyecto_id, nombre)
);
CREATE TABLE lote_plan_pago (
    lote_id BIGINT NOT NULL REFERENCES lote(id) ON DELETE CASCADE,
    plan_pago_id BIGINT NOT NULL REFERENCES plan_pago(id) ON DELETE RESTRICT,
    PRIMARY KEY (lote_id, plan_pago_id)
);
CREATE TABLE cliente (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_documento VARCHAR(20) NOT NULL,
    numero_documento VARCHAR(30) NOT NULL,
    nombre VARCHAR(160) NOT NULL,
    telefono VARCHAR(30),
    correo VARCHAR(120),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_cliente_documento UNIQUE (tipo_documento, numero_documento)
);
CREATE TABLE cliente_relacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    relacionado_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('COTITULAR','CONYUGE','OTRO')),
    CHECK (cliente_id <> relacionado_id),
    UNIQUE (cliente_id, relacionado_id, tipo)
);
CREATE TABLE cliente_documento (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    tipo VARCHAR(30) NOT NULL,
    lado VARCHAR(10) NOT NULL CHECK (lado IN ('ANVERSO','REVERSO')),
    ruta_privada VARCHAR(500) NOT NULL,
    fecha_carga TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (cliente_id, tipo, lado)
);
CREATE TABLE separacion (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES lote(id) ON DELETE RESTRICT,
    cliente_id BIGINT NOT NULL REFERENCES cliente(id) ON DELETE RESTRICT,
    asesor_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    monto NUMERIC(14,2) NOT NULL CHECK (monto > 0),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
    estado VARCHAR(20) NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA','CONFIRMADA','ANULADA','VENCIDA')),
    observacion VARCHAR(500)
);
-- Restricción final ante dos solicitudes simultáneas sobre el mismo lote.
CREATE UNIQUE INDEX uq_separacion_activa_lote ON separacion(lote_id) WHERE estado = 'ACTIVA';
CREATE TABLE venta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    separacion_id BIGINT NOT NULL UNIQUE REFERENCES separacion(id) ON DELETE RESTRICT,
    responsable_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    precio_final NUMERIC(14,2) NOT NULL CHECK (precio_final > 0),
    inicial NUMERIC(14,2) NOT NULL CHECK (inicial > 0),
    contrato_firmado BOOLEAN NOT NULL CHECK (contrato_firmado = TRUE),
    fecha_venta DATE NOT NULL
);
CREATE TABLE ficha_comercial (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES lote(id) ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    version INTEGER NOT NULL CHECK (version > 0),
    fecha_generacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    ruta_privada VARCHAR(500),
    UNIQUE (lote_id, version)
);
CREATE TABLE historial_lote (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lote_id BIGINT NOT NULL REFERENCES lote(id) ON DELETE RESTRICT,
    usuario_id BIGINT NOT NULL REFERENCES usuario(id) ON DELETE RESTRICT,
    separacion_id BIGINT REFERENCES separacion(id) ON DELETE RESTRICT,
    estado_anterior VARCHAR(20) NOT NULL,
    estado_nuevo VARCHAR(20) NOT NULL,
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT now(),
    motivo VARCHAR(200) NOT NULL,
    CHECK (estado_anterior <> estado_nuevo),
    CHECK (estado_anterior IN ('DISPONIBLE','RESERVADO','VENDIDO','NO_DISPONIBLE')),
    CHECK (estado_nuevo IN ('DISPONIBLE','RESERVADO','VENDIDO','NO_DISPONIBLE'))
);

CREATE INDEX ix_etapa_proyecto ON etapa(proyecto_id);
CREATE INDEX ix_manzana_etapa ON manzana(etapa_id);
CREATE INDEX ix_lote_manzana_estado ON lote(manzana_id, estado);
CREATE INDEX ix_plan_proyecto ON plan_pago(proyecto_id);
CREATE INDEX ix_cliente_relacion_cliente ON cliente_relacion(cliente_id);
CREATE INDEX ix_cliente_documento_cliente ON cliente_documento(cliente_id);
CREATE INDEX ix_separacion_cliente_fecha ON separacion(cliente_id, fecha_registro DESC);
CREATE INDEX ix_separacion_asesor_fecha ON separacion(asesor_id, fecha_registro DESC);
CREATE INDEX ix_historial_lote_fecha ON historial_lote(lote_id, fecha_cambio DESC);

COMMIT;
